def add_heading(text, style, level=0):
    key = "h_" + hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph(f'<a name="{key}"/>{text}', style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def h1(text):
    story.append(CondPageBreak((PAGE_H - 2 * MARGIN) * 0.25))
    story.append(add_heading(text, S_H1, 0))


def h2(text):
    story.append(add_heading(text, S_H2, 1))


def body(text):
    story.append(Paragraph(text, S_BODY))


def bullet(text):
    story.append(Paragraph(f"• {text}", S_BULLET))


def callout(text):
    tbl = Table([[Paragraph(text, S_CALL)]], colWidths=[AVAIL_W])
    tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
        ("LINEBEFORE", (0, 0), (0, -1), 3, ACCENT),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
    ]))
    story.append(Spacer(1, 6))
    story.append(tbl)
    story.append(Spacer(1, 10))


def make_table(header, rows, ratios, caption=None, align_center_cols=None):
    align_center_cols = align_center_cols or []
    widths = [r * AVAIL_W for r in ratios]
    data = [[Paragraph(f"<b>{c}</b>", S_TH) for c in header]]
    for r in rows:
        cells = []
        for i, c in enumerate(r):
            cells.append(Paragraph(str(c), S_TDC if i in align_center_cols else S_TD))
        data.append(cells)
    t = Table(data, colWidths=widths, hAlign="CENTER", repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i),
                      colors.white if i % 2 == 1 else TABLE_STRIPE))
    t.setStyle(TableStyle(style))
    story.append(Spacer(1, 10))
    story.append(t)
    if caption:
        story.append(Spacer(1, 4))
        story.append(Paragraph(caption, S_CAPTION))
    story.append(Spacer(1, 10))


def chart(path, caption, max_h=250):
    from PIL import Image as PILImage
    w, h = PILImage.open(path).size
    ratio = min(AVAIL_W / w, max_h / h, 1.0)
    img = Image(path, width=w * ratio, height=h * ratio)
    story.append(Spacer(1, 12))
    story.append(KeepTogether([img, Spacer(1, 6),
                               Paragraph(caption, S_CAPTION)]))
    story.append(Spacer(1, 12))


